#!/usr/bin/env python3
"""Generate widths_gen.go: the advance widths of the Inter font gnoweb serves.

The diagrams size their boxes from these widths, so the text the browser sets
in the same font fits them. Run `make mermaid-widths` in gno.land/pkg/gnoweb
after the font changes (needs `pip install fonttools brotli`).

Inter is by Rasmus Andersson, https://rsms.me/inter, under the SIL Open Font
License 1.1.
"""

import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

FONT = "../../public/fonts/intervar/Intervar.woff2"
# Regular and semibold, at the optical size of 14px text.
WEIGHTS = (400, 600)


def widths(font, weight):
    font = instancer.instantiateVariableFont(font, {"wght": weight, "opsz": 14})
    upem = font["head"].unitsPerEm
    hmtx = font["hmtx"]
    # Control characters never reach a label.
    return {cp: round(hmtx[g][0] * 1000 / upem) for cp, g in font.getBestCmap().items() if cp >= 0x20}


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), FONT)
    tables = [widths(TTFont(path), w) for w in WEIGHTS]
    version = TTFont(path)["name"].getDebugName(5)
    out = sys.stdout
    out.write("// Code generated by gen_widths.py from %s (%s). DO NOT EDIT.\n\n" % (os.path.basename(FONT), version))
    out.write("package mermaid\n\n")
    out.write("// Inter is by Rasmus Andersson (https://rsms.me/inter), under the SIL Open\n")
    out.write("// Font License 1.1.\n\n")
    out.write("// interWidths maps a rune to its advance width in Inter, in thousandths of\n")
    out.write("// an em, at weights %d and %d.\n" % WEIGHTS)
    out.write("var interWidths = map[rune][2]uint16{\n")
    for cp in sorted(tables[0]):
        out.write("\t0x%04X: {%d, %d},\n" % (cp, tables[0][cp], tables[1][cp]))
    out.write("}\n")


if __name__ == "__main__":
    main()
